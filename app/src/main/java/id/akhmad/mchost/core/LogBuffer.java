package id.akhmad.mchost.core;

import java.text.SimpleDateFormat;
import java.util.ArrayDeque;
import java.util.ArrayList;
import java.util.Date;
import java.util.List;
import java.util.Locale;
import java.util.regex.Pattern;

/** Ring buffer of console lines with increasing sequence numbers for polling. */
public class LogBuffer {
    private static final Pattern ANSI = Pattern.compile("\u001B\\[[;\\d]*[ -/]*[@-~]");

    public static final class Line {
        public final long seq;
        public final String text;

        Line(long seq, String text) {
            this.seq = seq;
            this.text = text;
        }
    }

    private final ArrayDeque<Line> lines = new ArrayDeque<>();
    private final int capacity;
    private long seq = 0;

    public LogBuffer(int capacity) {
        this.capacity = capacity;
    }

    public synchronized void add(String text) {
        if (text == null) return;
        text = ANSI.matcher(text).replaceAll("");
        lines.addLast(new Line(++seq, text));
        while (lines.size() > capacity) lines.removeFirst();
    }

    /** Message generated by the panel itself. */
    public void panel(String msg) {
        String t = new SimpleDateFormat("HH:mm:ss", Locale.US).format(new Date());
        add("[" + t + "] [Panel] " + msg);
    }

    public synchronized List<Line> since(long after, int max) {
        List<Line> out = new ArrayList<>();
        for (Line l : lines) {
            if (l.seq > after) out.add(l);
        }
        if (out.size() > max) out = new ArrayList<>(out.subList(out.size() - max, out.size()));
        return out;
    }

    public synchronized long last() {
        return seq;
    }
}
